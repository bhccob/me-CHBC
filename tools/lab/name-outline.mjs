// LAB ONLY (throwaway): writes src/lab/concepts/name-outline.ts, the outline of BOB / CHUNG in Barlow 800 as SVG path
// data in em units, laid out as the lab's .lab-name sets it (two lines, line-height 0.82, letter-spacing -0.04em), so
// concept C's line can trace the real letters over the real DOM text.  Run: node tools/lab/name-outline.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import opentype from 'opentype.js';

const buf = readFileSync('node_modules/@fontsource/barlow/files/barlow-latin-800-normal.woff');
const font = opentype.parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength));
const upm = font.unitsPerEm;
const LINE = 0.82;
const TRACK = -0.04;
// The CSS content area is hhea ascent minus descent; the line box's half-leading centres it.
const asc = font.tables.hhea.ascender / upm;
const desc = font.tables.hhea.descender / upm;
const baseline = (LINE - (asc - desc)) / 2 + asc;

const lines = ['BOB', 'CHUNG'];
const parts = [];
let width = 0;
lines.forEach((text, row) => {
  let x = 0;
  for (const ch of text) {
    const glyph = font.charToGlyph(ch);
    const path = glyph.getPath(x * upm, (row * LINE + baseline) * upm, upm);
    parts.push(path.toPathData(1));
    x += glyph.advanceWidth / upm + TRACK;
  }
  width = Math.max(width, x - TRACK);
});
const scaled = parts.join(' ');
const out = `/** LAB ONLY (throwaway). Generated by tools/lab/name-outline.mjs: BOB / CHUNG in Barlow 800, in em × ${upm}. */
export const NAME_OUTLINE = { upm: ${upm}, width: ${(width).toFixed(4)}, height: ${(LINE * 2).toFixed(4)}, d: ${JSON.stringify(scaled)} } as const;
`;
writeFileSync('src/lab/concepts/name-outline.ts', out);
console.log(`upm ${upm}, ascender ${asc.toFixed(3)}, descender ${desc.toFixed(3)}, baseline ${baseline.toFixed(3)} em, width ${width.toFixed(3)} em, ${scaled.length} chars`);
